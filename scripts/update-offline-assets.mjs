import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';

const docs = new URL('../docs/', import.meta.url);
const workerFile = 'offline-worker.js';
const names = (await readdir(docs)).filter((name) => /\.(?:html|mjs|css|svg|png|webmanifest)$/.test(name)).sort();
const assets = await Promise.all(names.map(async (name) => {
  const content = await readFile(new URL(name, docs));
  return [name, `sha256-${createHash('sha256').update(content).digest('base64')}`];
}));
const worker = await readFile(new URL(workerFile, docs));
const revision = createHash('sha256').update(JSON.stringify(assets)).update(worker).digest('hex').slice(0, 20);
const list = assets.map((asset) => `    ${JSON.stringify(asset)}`).join(',\n');
const output = `// Generated by scripts/update-offline-assets.mjs.\nself.npPosStatic = {\n  revision: '${revision}',\n  assets: [\n${list}\n  ],\n};\n`;
const target = new URL('offline-assets.js', docs);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) {
    throw new Error('Offline asset data is stale. Run node scripts/update-offline-assets.mjs.');
  }
} else {
  await writeFile(target, output);
}
